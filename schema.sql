-- The Stage Café & Cake Bar: orders table
-- Run this script in Supabase Dashboard > SQL Editor.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  customer_name text not null,
  phone text not null,
  fulfilment text not null check (fulfilment in ('Delivery','Pickup')),
  address text,
  notes text,
  payment_method text not null default 'Cash on Delivery',
  items jsonb not null,
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'New'
);

alter table public.orders enable row level security;
-- Customers may submit new orders from the public website.
drop policy if exists "Allow customers to place orders" on public.orders;
create policy "Allow customers to place orders"
on public.orders for insert
to anon, authenticated
with check (
  customer_name <> '' and phone <> '' and
  fulfilment in ('Delivery','Pickup') and
  payment_method = 'Cash on Delivery' and total >= 0
);
-- Do not add a public SELECT policy: customer/order data should remain private.
